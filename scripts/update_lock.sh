#!/usr/bin/env bash
# Regenerate requirements.lock: exact versions of every package (including
# transitive ones) that a clean install of the runtime and test requirements
# resolves to, on the same base image the MCP Dockerfile uses.
#
#   scripts/update_lock.sh
#
# The Dockerfile installs with `-c requirements.lock`, so rebuilds are
# reproducible; edit requirements*.txt for intent, then rerun this to move pins.
set -euo pipefail
cd "$(dirname "$0")/.."
base_image=$(sed -n 's/^FROM \([^ ]*\).*/\1/p' Dockerfile.mcp | head -1)
docker run --rm -v "$PWD:/src:ro" -w /src "$base_image" sh -c '
  pip install --quiet --no-cache-dir --root-user-action=ignore \
    -r requirements.txt -r requirements-test.txt >/dev/null &&
  echo "# Generated by scripts/update_lock.sh from requirements.txt and requirements-test.txt" &&
  echo "# on $(python --version 2>&1) ('"$base_image"'). Do not edit by hand." &&
  pip freeze --all --exclude pip --exclude setuptools --exclude wheel | LC_ALL=C sort -f
' > requirements.lock.tmp
mv requirements.lock.tmp requirements.lock
echo "requirements.lock: $(grep -c '==' requirements.lock) pinned packages"
